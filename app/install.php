<?php
declare(strict_types=1);

/** One-time web installer: creates config.php, the database tables, default content and the first admin. */
function run_installer(): never
{
    $errors = [];
    $warnings = [];
    if (!is_file(PUBLIC_DIR . '/.htaccess')) {
        $warnings[] = 'The hidden .htaccess file is missing from ' . PUBLIC_DIR . '. Upload it (in File Manager: Settings → Show Hidden Files) or every page except the homepage will show "Not Found".';
    }
    if (version_compare(PHP_VERSION, '8.1.0', '<')) {
        $warnings[] = 'PHP ' . PHP_VERSION . ' is too old. Choose PHP 8.1 or newer in cPanel → MultiPHP Manager.';
    }
    if (!extension_loaded('pdo_mysql')) {
        $warnings[] = 'The pdo_mysql PHP extension is not enabled. Turn it on in cPanel → Select PHP Version → Extensions.';
    }
    $scriptDir = rtrim(str_replace('\\', '/', dirname((string)($_SERVER['SCRIPT_NAME'] ?? '/'))), '/');
    $scheme = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off') ? 'https' : 'http';
    $old = [
        'site_url' => $scheme . '://' . ($_SERVER['HTTP_HOST'] ?? 'www.cybercraft.biz'),
        'db_host' => 'localhost', 'db_port' => '3306', 'db_name' => '', 'db_user' => '',
        'admin_name' => '', 'admin_email' => '',
    ];

    if (is_post()) {
        foreach ($old as $k => $_) {
            $old[$k] = post($k);
        }
        $dbPass = (string)($_POST['db_pass'] ?? '');
        $pw = (string)($_POST['admin_password'] ?? '');

        if (!csrf_check()) $errors[] = 'Your session expired. Please submit again.';
        if (!preg_match('#^https?://#', $old['site_url'])) $errors[] = 'Site address must start with http:// or https://';
        if ($old['db_name'] === '' || $old['db_user'] === '') $errors[] = 'Enter the database name and user from cPanel → MySQL Databases.';
        if (mb_strlen($old['admin_name']) < 2) $errors[] = 'Enter the administrator\'s name.';
        if (!filter_var($old['admin_email'], FILTER_VALIDATE_EMAIL)) $errors[] = 'Enter a valid administrator email.';
        if (strlen($pw) < 10) $errors[] = 'The administrator password must be at least 10 characters.';
        if ($pw !== (string)($_POST['admin_password2'] ?? '')) $errors[] = 'The two passwords do not match.';
        if (!is_writable(APP_DIR) || !is_writable(APP_DIR . '/storage')) $errors[] = 'The app folder and app/storage must be writable (permissions 755).';

        $db = ['host' => $old['db_host'] ?: 'localhost', 'port' => (int)($old['db_port'] ?: 3306), 'name' => $old['db_name'], 'user' => $old['db_user'], 'pass' => $dbPass];

        if (!$errors) {
            try {
                $pdo = Db::connect($db);
            } catch (Throwable $ex) {
                $errors[] = 'Could not connect to the database. Check the details and that the user is added to the database with ALL PRIVILEGES. (' . $ex->getMessage() . ')';
            }
        }

        if (!$errors) {
            Db::init($db);
            $schema = (string)file_get_contents(APP_DIR . '/schema.sql');
            $schema = preg_replace('/^\s*--.*$/m', '', $schema) ?? '';
            foreach (array_filter(array_map('trim', explode(';', $schema))) as $stmt) {
                Db::pdo()->exec($stmt);
            }
            Seed::run();
            Upgrade::run(); // brings content from an earlier version (or an older SQL import) up to date
            Db::exec('INSERT INTO settings (k, v) VALUES (?, ?) ON DUPLICATE KEY UPDATE v = VALUES(v)', ['site_url', rtrim($old['site_url'], '/')]);
            if (!Db::value('SELECT id FROM users WHERE email = ?', [strtolower($old['admin_email'])])) {
                Db::insert('users', [
                    'name' => $old['admin_name'], 'email' => strtolower($old['admin_email']),
                    'password_hash' => password_hash($pw, PASSWORD_DEFAULT), 'role' => 'admin', 'created_at' => now(),
                ]);
            }

            $config = [
                'db' => $db,
                'base_path' => $scriptDir === '/' ? '' : $scriptDir,
                'timezone' => 'UTC',
                'debug' => false,
            ];
            $php = "<?php\n// Generated by the installer on " . date('Y-m-d H:i') . ". Keep this file private.\nreturn " . var_export($config, true) . ";\n";
            file_put_contents(APP_DIR . '/config.php', $php, LOCK_EX);
            @chmod(APP_DIR . '/config.php', 0600);
            file_put_contents(APP_DIR . '/storage/installed.lock', date('c'));

            header('Location: ' . ($config['base_path'] . '/admin/login?installed=1'), true, 303);
            exit;
        }
    }

    $token = csrf_token();
    header('Content-Type: text/html; charset=utf-8');
    ?>
<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="robots" content="noindex">
<title>Install CyberCraft website</title>
<style>
body{font-family:system-ui,-apple-system,"Segoe UI",sans-serif;background:#f4f6f9;color:#0f1d33;margin:0;padding:40px 16px}
.box{max-width:620px;margin:0 auto;background:#fff;border:1px solid #d9dfe8;border-radius:14px;padding:32px}
h1{margin:0 0 6px;font-size:1.6rem}p{color:#566278}fieldset{border:1px solid #d9dfe8;border-radius:10px;margin:18px 0;padding:14px 16px}
legend{font-weight:700;padding:0 6px}label{display:block;font-size:.9rem;font-weight:600;margin:10px 0 4px}
input{width:100%;box-sizing:border-box;padding:10px 12px;border:1px solid #c7cfdc;border-radius:8px;font:inherit}
.row{display:grid;grid-template-columns:2fr 1fr;gap:12px}button{background:#0b5fae;color:#fff;border:0;border-radius:8px;padding:12px 20px;font:inherit;font-weight:700;cursor:pointer;margin-top:10px}
.warn{background:#fff4dc;color:#7a4b00;border-radius:8px;padding:10px 14px;margin:12px 0}.err{background:#fde8e8;color:#8a1c1c;border-radius:8px;padding:10px 14px;margin:12px 0}.err li{margin:2px 0}small{color:#566278}
</style></head><body><div class="box">
<h1>Install CyberCraft</h1>
<p>Create a MySQL database and user in cPanel → <b>MySQL® Databases</b>, add the user to the database with <b>All Privileges</b>, then fill in the form.</p>
<?php if ($warnings): ?><div class="warn"><b>Check before continuing:</b><ul><?php foreach ($warnings as $w): ?><li><?= e($w) ?></li><?php endforeach ?></ul></div><?php endif ?>
<?php if ($errors): ?><div class="err"><ul><?php foreach ($errors as $er): ?><li><?= e($er) ?></li><?php endforeach ?></ul></div><?php endif ?>
<form method="post" autocomplete="off">
<input type="hidden" name="_csrf" value="<?= e($token) ?>">
<fieldset><legend>Website</legend>
<label for="site_url">Site address</label><input id="site_url" name="site_url" value="<?= e($old['site_url']) ?>" required>
</fieldset>
<fieldset><legend>Database</legend>
<div class="row"><div><label for="db_host">Host</label><input id="db_host" name="db_host" value="<?= e($old['db_host']) ?>"></div>
<div><label for="db_port">Port</label><input id="db_port" name="db_port" value="<?= e($old['db_port']) ?>"></div></div>
<label for="db_name">Database name</label><input id="db_name" name="db_name" value="<?= e($old['db_name']) ?>" placeholder="cpaneluser_cybercraft" required>
<label for="db_user">Database user</label><input id="db_user" name="db_user" value="<?= e($old['db_user']) ?>" required>
<label for="db_pass">Database password</label><input id="db_pass" type="password" name="db_pass">
</fieldset>
<fieldset><legend>First administrator</legend>
<label for="admin_name">Name</label><input id="admin_name" name="admin_name" value="<?= e($old['admin_name']) ?>" required>
<label for="admin_email">Email</label><input id="admin_email" type="email" name="admin_email" value="<?= e($old['admin_email']) ?>" required>
<label for="admin_password">Password <small>(at least 10 characters)</small></label><input id="admin_password" type="password" name="admin_password" minlength="10" required>
<label for="admin_password2">Repeat password</label><input id="admin_password2" type="password" name="admin_password2" minlength="10" required>
</fieldset>
<button type="submit">Install website</button>
</form></div></body></html>
<?php
    exit;
}
